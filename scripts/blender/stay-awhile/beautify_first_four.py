def repair_tea_deck_overlap(col):
    """Undo a broad legacy rail edit that skewed one deck plank over its neighbors."""
    from collections import deque
    obj=next(o for o in col.objects if o.type=='MESH' and not o.get('beautyPass'))
    if obj.get('beautyDeckOverlapRepair'):return
    mesh=obj.data
    candidate=[]
    for poly in mesh.polygons:
        pts=[G(mesh.vertices[i].co) for i in poly.vertices]
        if (all(abs(v[1]-.3)<.006 for v in pts) and
            min(v[0] for v in pts)<1.1 and max(v[0] for v in pts)>1.9 and
            max(v[2] for v in pts)-min(v[2] for v in pts)>3.5):candidate.append(poly)
    if len(candidate)!=1:raise RuntimeError(f'Expected one skewed T01 plank, found {len(candidate)} in {obj.name}')
    adjacency=defaultdict(set)
    for edge in mesh.edges:
        u,v=edge.vertices;adjacency[u].add(v);adjacency[v].add(u)
    group=set(candidate[0].vertices);todo=deque(group)
    while todo:
        for neighbor in adjacency[todo.popleft()]:
            if neighbor not in group:group.add(neighbor);todo.append(neighbor)
    count=0
    for index in group:
        vertex=mesh.vertices[index];x,y,z=G(vertex.co)
        if z< -1.9 and y<=.31 and .95<x<1.35:
            vertex.co=B(((x+.35)/.8,y,z));count+=1
    if count<2:raise RuntimeError(f'No distorted deck corners repaired in {obj.name}')
    mesh.update();obj['beautyDeckOverlapRepair']=True

