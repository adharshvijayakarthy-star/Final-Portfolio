def color(h):
    return tuple(linear(int(h[i:i+2], 16) / 255) for i in (0, 2, 4)) + (1,)

def mat_for(key, lod):
    name="SA_M_" + key + ("_MOBILE" if lod == "mobile" and key in ("BARK", "PAPER") else "")
    m=bpy.data.materials.get(name) or bpy.data.materials.get("SA_M_"+key)
    if m is None:
        m=bpy.data.materials.new(name);m.use_nodes=True
        m.diffuse_color=color(PALETTE[key])
        m.node_tree.nodes['Principled BSDF'].inputs['Base Color'].default_value=color(PALETTE[key])
    return m

def beauty_atlas(lod):
    """Packed route-local wood grain; the pre-existing shared atlas stays intact."""
    size=512 if lod=='mobile' else 1024
    path=HERE/f'beauty-timber.{lod}.png'
    if not path.exists() or path.stat().st_size>25000:
        raw=bytearray()
        for y in range(size):
            raw.append(0)
            if y<size//2:
                phase=int(2*math.sin(y/70))
                for x in range(size):
                    u=x*1024/size+phase
                    grain=7*math.sin(u/5.7)+4*math.sin(u/17.8)+2*math.sin(u/1.9)
                    shade=int(grain)
                    raw.extend((max(0,min(255,118+shade)),max(0,min(255,88+shade)),max(0,min(255,65+shade))))
            else:
                shade=int(math.sin(y/37))
                raw.extend(bytes((237+shade,232+shade,217+shade))*size)
        def chunk(kind,payload):
            return struct.pack('>I',len(payload))+kind+payload+struct.pack('>I',zlib.crc32(kind+payload)&0xffffffff)
        png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',size,size,8,2,0,0,0))
        png+=chunk(b'IDAT',zlib.compress(bytes(raw),9))+chunk(b'IEND',b'')
        path.write_bytes(png)
    image=bpy.data.images.get('SA_BEAUTY_TIMBER_'+lod.upper())
    if not image:
        image=bpy.data.images.load(str(path),check_existing=False)
        image.name='SA_BEAUTY_TIMBER_'+lod.upper()
        image.pack()
    return image

def setup_materials():
    for key, h in PALETTE.items():
        for suffix in ("", "_MOBILE"):
            m = bpy.data.materials.get("SA_M_" + key + suffix)
            if not m or m.library: continue
            m.diffuse_color = color(h)
            p = m.node_tree.nodes.get("Principled BSDF")
            if not p: continue
            if key not in ("BARK", "PAPER"):
                p.inputs["Base Color"].default_value = color(h)
                for mix in m.node_tree.nodes:
                    if mix.type=='MIX_RGB' and mix.blend_type=='MULTIPLY' and not mix.inputs[1].is_linked:
                        mix.inputs[1].default_value=color(h)
            if key=='BARK':
                image=beauty_atlas('mobile' if suffix else 'desktop')
                for node in m.node_tree.nodes:
                    if node.type=='TEX_IMAGE':node.image=image
            p.inputs["Roughness"].default_value = {"WATER": .19, "STONE": .91, "BARK": .76, "PAPER": .92, "LEAF": .83}.get(key, .86)
            if key=="WATER":p.inputs["Metallic"].default_value=.08
            nodes = m.node_tree.nodes
            if not any(n.type == 'VERTEX_COLOR' for n in nodes):
                v = nodes.new("ShaderNodeVertexColor"); v.name = "SA_VERTEX_TONE"; v.layer_name = "COLOR_0"
                mul = nodes.new("ShaderNodeMixRGB"); mul.name = "SA_TONE_MULTIPLY"; mul.blend_type = 'MULTIPLY'; mul.inputs[0].default_value = 1
                upstream = p.inputs["Base Color"].links[0].from_socket if p.inputs["Base Color"].is_linked else None
                if upstream: m.node_tree.links.new(upstream, mul.inputs[1])
                else: mul.inputs[1].default_value = p.inputs["Base Color"].default_value
                m.node_tree.links.new(v.outputs["Color"], mul.inputs[2]); m.node_tree.links.new(mul.outputs[0], p.inputs["Base Color"])

