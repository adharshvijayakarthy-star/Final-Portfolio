def terrain_height(x,z,low=False):
    # The actual G01 mesh contains a later camera-rail flattening pass. Ray
    # against that delivered surface instead of reconstructing the older
    # procedural height equation; the equation leaves planting in mid-air.
    col=bpy.data.collections['SA_G01_MOBILE' if low else 'SA_G01_DESKTOP']
    ground=next(o for o in col.objects if o.type=='MESH' and not o.get('beautyPass'))
