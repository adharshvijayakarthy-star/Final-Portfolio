def shaped_path(a):
    variants=('STRAIGHT','BEND','JUNCTION')
    for vi,role in enumerate(variants):
        parent=original_parent('G02',a.lod,role)
        for i in range(6):
            t=(i+.5)/6
            if vi==0:x,z=0,2-t*4
            elif vi==1:x,z=4*(1-math.cos(t*math.pi/6)),2-8*math.sin(t*math.pi/6)
            else:
                ang=(-math.pi/2,math.pi/6,5*math.pi/6)[i//2];r=.6+(i%2)*1.15;x,z=math.cos(ang)*r,math.sin(ang)*r
            rng=random.Random(vi*41+i*13)
            x+=rng.uniform(-.19,.19);z+=rng.uniform(-.055,.055)
            a.stone((x,-.115+rng.uniform(-.009,.009),z),(.72+rng.uniform(-.10,.08),.085,.285+rng.uniform(-.025,.035)),parent=parent,seed=vi*31+i,
                    sides=5 if a.low else 7)
            if not a.low and i%2==0:
                a.stone((x+(.85 if i%4 else -.87),-.12,z+.1),(.17,.035,.15),parent=parent,seed=80+i,sides=5)
        # Fine moss at one edge; kept below the pedestrian crown.
        for i in range(4 if not a.low else 0):
            z=1.55-i*.95; x=(.76 if i%3 else -.83)+ .11*math.sin(i*3+vi)
            a.leaf((x,-.055,z),(x+.14,.075,z-.09),.12,'LEAF',parent,.85,i)

def sakura(a):
    rng=random.Random(710)
    trunk=[(0,0,0),(-.12,1.5,.06),(.06,2.9,-.17),(.3,4.08,-.24),(.22,5.05,-.28)]
    a.tube(trunk,[.35,.27,.19,.11,.045],seed=2)
    for i,(ang,reach,lift) in enumerate(((.25,2.9,1.55),(2.55,2.65,1.8),(4.55,3.05,1.4))):
        pivot=original_parent('G03',a.lod,'SWAY_'+chr(65+i))
        if pivot is None:continue
        d=Vector((math.cos(ang),0,math.sin(ang)))
        tip=Vector((d.x*reach,lift+1.4,d.z*reach))
        a.tube([(0,0,0),(d.x*.8,.75,d.z*.8),(d.x*reach*.7,lift,d.z*reach*.7),tip],
               [.18,.13,.075,.018],parent=pivot,seed=i+3)
        count=7 if a.low else 13
        for j in range(count):
            q=(j+.4)/(count+.7)
            side=(-1 if j%2 else 1)
            start=Vector((d.x*reach*(.2+.64*q),.4+(lift+.65)*q,d.z*reach*(.2+.64*q)))
            perp=Vector((-d.z,0,d.x));end=start+d*(.3+.45*(1-q))+perp*side*(.4+.65*(1-q))+Vector((0,.28+.32*rng.random(),0))
            a.tube([start,start.lerp(end,.54),end],[.055,.032,.008],parent=pivot,seed=20+i*20+j)
            # Distinct branch-led blossom sprays, with air between clusters.
            petals=5 if a.low else 9
            for k in range(petals):
                theta=k*2.4+.36*j;rad=(.11+.17*rng.random())*(.7+q*.3)
                c=end+Vector((math.cos(theta)*rad,rng.uniform(-.08,.11),math.sin(theta)*rad))
                a.leaf(c,c+Vector((math.cos(theta)*.13,.035,math.sin(theta)*.12)),.105 if not a.low else .14,'SAKURA',pivot,.75+.23*rng.random(),k)
        # Airy blossom masses follow the branch ends, leaving holes through
        # the crown rather than a single spherical cap.
        for j in range(4 if a.low else 7):
            q=.43+j*(.40/(3 if a.low else 6))
            perp=Vector((-d.z,0,d.x))
            c=d*(reach*q)+perp*((-1 if j%2 else 1)*(.43+.14*(j%3)))+Vector((0,1.25+lift*q+.13*(j%3),0))
            a.crown(c,(.39+.07*(j%2),.29+.055*(j%3),.35+.05*(j%2)),'SAKURA',pivot,seed=930+i*17+j)
    # Old bark texture alone reads flat in silhouette: exposed lateral scars.
    if not a.low:
        for j in range(8):
            y=.5+j*.46;a.tube([(.21,y,-.01),(.24,y+.14,-.04)],[.017,.01],parent=a.root,seed=180+j)

