def scene_route(route):
    source=HERE/ROUTES[route]
    bpy.ops.wm.open_mainfile(filepath=str(source),load_ui=False)
    setup_materials();tune_light(route)
    owned={"garden":['G01','G02','G03','G04','G05','G06','G07','G11','G14'],"person":['P01','P02','P03'],"builder":['B01','B02','B03','B05'],"thinker":['T01','T02']}[route]
    for aid in owned:
        for lod in ('desktop','mobile'):
            a=Sculpt(aid,lod)
            for o in list(a.col.objects):
                if o.get('beautyPass',0)>=2:bpy.data.objects.remove(o,do_unlink=True)
            # Only entirely rebuilt kits have their original meshes removed.
            if aid in ('G02','G03','G04','G05','G06','G07','G11','P03','T02'):clear_meshes(aid,lod)
            if aid=='G02':shaped_path(a)
            elif aid=='G03':sakura(a)
            elif aid=='G04':shrub(a)
            elif aid=='G05':grass(a)
            elif aid=='G06':stone_kit(a)
            elif aid=='G07':water(a)
            elif aid=='G11':distant_bank(a)
            else:route_environment(a,route)
            a.flush()
            if aid=='G14':
                for o in a.col.objects:
                    if o.type!='MESH' or o.get('beautyPass') or o.get('beautyMarkerProportions'):continue
                    for vertex in o.data.vertices:
                        vertex.co.x*=.72
                        vertex.co.y*=.74
                        vertex.co.z*=1.05
                    o.data.update()
                    o['beautyMarkerProportions']=True
            if aid=='T01':repair_tea_deck_overlap(a.col)
    # The full garden floor uses sober greens with soft variation, retaining
    # the original topography/zone flattening and all route placements.
    if route=='garden':
        for lod in ('DESKTOP','MOBILE'):
            col=bpy.data.collections['SA_G01_'+lod]
            for o in col.objects:
                if o.type!='MESH':continue
                attr=o.data.color_attributes.get('COLOR_0')
                if not attr:continue
                for i,v in enumerate(o.data.vertices):
                    x,y,z=G(v.co)
                    t=.70+.16*math.sin(x*.17+z*.12)+.10*math.cos(x*.39-z*.28)
